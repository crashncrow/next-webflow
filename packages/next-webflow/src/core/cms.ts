/** Connects the CMS functions to a framework's cache. `src/next` provides the Next.js one. */
export interface CacheAdapter {
  /** `fetch` options for a cached read tagged with `tags`. */
  init(tags: string[]): FetchInit;
  /** Whether to read staged (draft) content instead of published content. */
  isDraft(): Promise<boolean>;
}

/** No caching, never draft. Used outside a framework (scripts, tests). */
export const noCache: CacheAdapter = {
  init: () => ({}),
  isDraft: async () => false,
};

export type ContentSource = "data" | "cdn";

export interface WebflowCmsConfig<S extends WebflowSchema | undefined = undefined>
  extends WebflowClientConfig {
  /** Runtime schema generated by `next-webflow typegen`. Without it, schemas are fetched from the API. */
  schema?: S;
  /** Needed only to look up collections without a generated schema. Defaults to `WEBFLOW_SITE_ID`. */
  siteId?: string | undefined;
  /**
   * Where published items are read from. `data` (default): Data API, relies on webhooks to
   * invalidate. `cdn`: Content Delivery API, cached up to 300 s by Webflow, no rate limit on hits.
   */
  source?: ContentSource | undefined;
  cache?: CacheAdapter | undefined;
  logger?: Pick<Console, "warn"> | undefined;
}

export type SortBy = "createdOn" | "lastPublished" | "lastUpdated" | "name" | "slug";

export interface FilterOperators {
  eq?: QueryValue;
  ne?: QueryValue;
  gt?: QueryValue;
  gte?: QueryValue;
  lt?: QueryValue;
  lte?: QueryValue;
  in?: string | readonly string[];
  nin?: string | readonly string[];
  contains?: string;
  ncontains?: string;
  exists?: boolean;
}

export interface ReadOptions {
  /** Locale to read; defaults to the primary locale. */
  cmsLocaleId?: string | undefined;
  signal?: AbortSignal | undefined;
}

export interface GetItemsOptions extends ReadOptions {
  /** Max items to return. Default: all (paginated transparently). */
  limit?: number | undefined;
  offset?: number | undefined;
  sortBy?: SortBy | undefined;
  sortOrder?: "asc" | "desc" | undefined;
  /** Keyed by field name (camelCase) or API slug, e.g. `{ featured: { eq: true } }`. */
  filter?: { [field: string]: FilterOperators | undefined } | undefined;
}

type Raw = { raw: true };
type NotRaw = { raw?: false | undefined };

type CollectionSlug<S extends WebflowSchema> = Extract<keyof S, string>;

/** Functions typed from a generated schema: collection slugs and item fields are inferred. */
export interface TypedWebflowCms<S extends WebflowSchema> {
  getItems<K extends CollectionSlug<S>>(collection: K, options: GetItemsOptions & Raw): Promise<WebflowRawItem[]>;
  getItems<K extends CollectionSlug<S>>(collection: K, options?: GetItemsOptions & NotRaw): Promise<ItemOf<S, K>[]>;
  getItemBySlug<K extends CollectionSlug<S>>(collection: K, slug: string, options: ReadOptions & Raw): Promise<WebflowRawItem | null>;
  getItemBySlug<K extends CollectionSlug<S>>(collection: K, slug: string, options?: ReadOptions & NotRaw): Promise<ItemOf<S, K> | null>;
  getItem<K extends CollectionSlug<S>>(collection: K, itemId: string, options: ReadOptions & Raw): Promise<WebflowRawItem | null>;
  getItem<K extends CollectionSlug<S>>(collection: K, itemId: string, options?: ReadOptions & NotRaw): Promise<ItemOf<S, K> | null>;
}

/** Functions without a generated schema: any collection slug, fields typed via the generic. */
export interface UntypedWebflowCms {
  getItems(collection: string, options: GetItemsOptions & Raw): Promise<WebflowRawItem[]>;
  getItems<F = UnknownFields>(collection: string, options?: GetItemsOptions & NotRaw): Promise<WebflowItem<F>[]>;
  getItemBySlug(collection: string, slug: string, options: ReadOptions & Raw): Promise<WebflowRawItem | null>;
  getItemBySlug<F = UnknownFields>(collection: string, slug: string, options?: ReadOptions & NotRaw): Promise<WebflowItem<F> | null>;
  getItem(collection: string, itemId: string, options: ReadOptions & Raw): Promise<WebflowRawItem | null>;
  getItem<F = UnknownFields>(collection: string, itemId: string, options?: ReadOptions & NotRaw): Promise<WebflowItem<F> | null>;
}

export type WebflowCms<S extends WebflowSchema | undefined> = [S] extends [WebflowSchema]
  ? TypedWebflowCms<S>
  : UntypedWebflowCms;

/** How long a schema fetched from the API is reused in memory (on top of the framework cache). */
const REMOTE_SCHEMA_TTL_MS = 60_000;

interface ReadContext {
  host: WebflowHost;
  draft: boolean;
  init(tags: string[]): FetchInit;
}

export function createWebflowCms<S extends WebflowSchema | undefined = undefined>(
  config: WebflowCmsConfig<S> = {},
  client: WebflowClient = createWebflowClient(config),
): WebflowCms<S> {
  const generated: WebflowSchema | undefined = config.schema;
  const source = config.source ?? "data";
  const cache = config.cache ?? noCache;
  const logger = config.logger ?? console;

  const remoteSchemas = new Map<string, { value: Promise<CollectionSchema>; expires: number }>();
  /** Collections whose generated schema turned out to be stale: use the API schema instead. */
  const stale = new Set<string>();
  const warned = new Set<string>();

  const warnOnce = (key: string, message: string) => {
    if (warned.has(key)) return;
    warned.add(key);
    logger.warn(`[next-webflow] ${message}`);
  };

  async function context(): Promise<ReadContext> {
    if (await cache.isDraft()) {
      // Staged content only exists on the Data API, and must never be cached.
      return { host: "data", draft: true, init: () => ({ cache: "no-store" }) };
    }
    return { host: source, draft: false, init: (tags) => cache.init(tags) };
  }

  function memo(key: string, load: () => Promise<CollectionSchema>): Promise<CollectionSchema> {
    const hit = remoteSchemas.get(key);
    if (hit && hit.expires > Date.now()) return hit.value;
    const value = load();
    remoteSchemas.set(key, { value, expires: Date.now() + REMOTE_SCHEMA_TTL_MS });
    value.catch(() => remoteSchemas.delete(key));
    return value;
  }

  const fetchSchemaById = (collectionId: string) =>
    memo(`id:${collectionId}`, async () =>
      schemaFromApi(
        await client.request<ApiCollection>(`/collections/${encodeURIComponent(collectionId)}`, {
          init: cache.init(schemaTags(collectionId)),
        }),
      ),
    );

  const fetchSchemaBySlug = (slug: string) =>
    memo(`slug:${slug}`, async () => {
      const siteId = config.siteId ?? readEnv(ENV.siteId);
      if (!siteId) {
        throw new WebflowConfigError(
          `No generated schema for collection "${slug}" and no site ID to look it up. ` +
            `Run \`npx next-webflow typegen\`, or set ${ENV.siteId}.`,
        );
      }
      const { collections } = await client.request<{ collections: ApiCollection[] }>(
        `/sites/${encodeURIComponent(siteId)}/collections`,
        { init: cache.init(schemaTags()) },
      );
      const match = collections.find((collection) => collection.slug === slug);
      if (!match) throw new WebflowConfigError(`Collection "${slug}" not found in site ${siteId}.`);
      return fetchSchemaById(match.id);
    });

  async function resolveCollection(slug: string): Promise<CollectionSchema> {
    const fromGenerated = generated?.[slug];
    if (fromGenerated && !stale.has(slug)) return fromGenerated;
    if (!fromGenerated) {
      warnOnce(
        `missing:${slug}`,
        `No generated schema for collection "${slug}"; fetching it from the API. ` +
          "Run `npx next-webflow typegen` to get types and avoid the extra requests.",
      );
      return fetchSchemaBySlug(slug);
    }
    return fetchSchemaById(fromGenerated.id);
  }

  /** Normalizes items; if the generated schema is stale, retries once with the API schema. */
  async function normalizeAll(
    slug: string,
    collection: CollectionSchema,
    raws: WebflowRawItem[],
  ): Promise<WebflowItem[]> {
    let results = raws.map((raw) => normalizeItem(raw, collection));
    let mismatch = mergeMismatches(results.map((result) => result.mismatch));

    if (mismatch && generated?.[slug] === collection) {
      warnOnce(
        `stale:${slug}`,
        `The generated schema for "${slug}" is out of date (${describe(mismatch)}). ` +
          "Using the live schema from the API; run `npx next-webflow typegen` to update your types.",
      );
      stale.add(slug);
      try {
        const fresh = await fetchSchemaById(collection.id);
        results = raws.map((raw) => normalizeItem(raw, fresh));
        mismatch = mergeMismatches(results.map((result) => result.mismatch));
      } catch (error) {
        warnOnce(
          `refresh:${slug}`,
          `Could not fetch the live schema for "${slug}" (${error instanceof Error ? error.message : String(error)}). ` +
            "Serving items with the generated schema.",
        );
      }
    }

    if (mismatch && mismatch.unknownOptions.length > 0) {
      warnOnce(
        `options:${slug}`,
        `Unknown Option IDs in "${slug}" (${describe({ unknownFields: [], unknownOptions: mismatch.unknownOptions })}); ` +
          "returning them as { id, name: undefined }.",
      );
    }
    return results.map((result) => result.item);
  }

  function buildQuery(collection: CollectionSchema, options: GetItemsOptions): QueryParams {
    const filter: Record<string, QueryValue> = {};
    for (const [key, operators] of Object.entries(options.filter ?? {})) {
      if (!operators) continue;
      const slug = collection.fields[key]?.slug ?? key;
      filter[slug] = Object.fromEntries(
        Object.entries(operators).filter(([, value]) => value !== undefined),
      ) as Record<string, QueryValue>;
    }
    return {
      sortBy: options.sortBy,
      sortOrder: options.sortOrder,
      cmsLocaleId: options.cmsLocaleId,
      ...(Object.keys(filter).length > 0 && { filter }),
    };
  }

  const itemsPath = (collectionId: string, draft: boolean) =>
    `/collections/${encodeURIComponent(collectionId)}/items${draft ? "" : "/live"}`;

  async function getItems(slug: string, options: GetItemsOptions & { raw?: boolean } = {}) {
    const [collection, ctx] = await Promise.all([resolveCollection(slug), context()]);
    const { items } = await client.paginate<WebflowRawItem>(itemsPath(collection.id, ctx.draft), {
      host: ctx.host,
      query: buildQuery(collection, options),
      limit: options.limit,
      offset: options.offset,
      signal: options.signal,
      init: ctx.init(listTags(collection.id)),
    });
    return options.raw ? items : normalizeAll(slug, collection, items);
  }

  async function getItemBySlug(slug: string, itemSlug: string, options: ReadOptions & { raw?: boolean } = {}) {
    const [collection, ctx] = await Promise.all([resolveCollection(slug), context()]);
    const { items } = await client.request<WebflowListResponse<WebflowRawItem>>(
      itemsPath(collection.id, ctx.draft),
      {
        host: ctx.host,
        query: { slug: itemSlug, cmsLocaleId: options.cmsLocaleId },
        signal: options.signal,
        init: ctx.init(slugLookupTags(collection.id, itemSlug)),
      },
    );
    const raw = items.find((item) => item.fieldData.slug === itemSlug);
    if (!raw) return null;
    if (options.raw) return raw;
    const [item] = await normalizeAll(slug, collection, [raw]);
    return item ?? null;
  }

  async function getItem(slug: string, itemId: string, options: ReadOptions & { raw?: boolean } = {}) {
    const [collection, ctx] = await Promise.all([resolveCollection(slug), context()]);
    const base = `/collections/${encodeURIComponent(collection.id)}/items/${encodeURIComponent(itemId)}`;
    const path = ctx.draft ? base : `${base}/live`;
    let raw: WebflowRawItem;
    try {
      raw = await client.request<WebflowRawItem>(path, {
        host: ctx.host,
        query: { cmsLocaleId: options.cmsLocaleId },
        signal: options.signal,
        init: ctx.init(itemTags(itemId)),
      });
    } catch (error) {
      if (error instanceof WebflowNotFoundError) return null;
      throw error;
    }
    if (options.raw) return raw;
    const [item] = await normalizeAll(slug, collection, [raw]);
    return item ?? null;
  }

  return { getItems, getItemBySlug, getItem } as unknown as WebflowCms<S>;
}

function mergeMismatches(mismatches: Array<SchemaMismatch | undefined>): SchemaMismatch | undefined {
  const present = mismatches.filter((mismatch): mismatch is SchemaMismatch => mismatch !== undefined);
  if (present.length === 0) return undefined;
  return {
    unknownFields: [...new Set(present.flatMap((mismatch) => mismatch.unknownFields))],
    unknownOptions: present.flatMap((mismatch) => mismatch.unknownOptions),
  };
}

function describe(mismatch: SchemaMismatch): string {
  const parts: string[] = [];
  if (mismatch.unknownFields.length > 0) parts.push(`unknown fields: ${mismatch.unknownFields.join(", ")}`);
  if (mismatch.unknownOptions.length > 0) {
    parts.push(`unknown options in: ${[...new Set(mismatch.unknownOptions.map((option) => option.field))].join(", ")}`);
  }
  return parts.join("; ");
}
