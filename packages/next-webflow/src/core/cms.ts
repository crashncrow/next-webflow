/** Connects the CMS functions to a framework's cache. `src/next` provides the Next.js one. */
export interface CacheAdapter {
  /** `fetch` options for a cached read tagged with `tags`. */
  init(tags: string[]): FetchInit;
  /** Whether to read staged (draft) content instead of published content. */
  isDraft(): Promise<boolean>;
  /** Whether this is a production build (prerendering). Enables build-time slug lookups from the list. */
  isBuild?(): boolean;
}

/** No caching, never draft. Used outside a framework (scripts, tests). */
export const noCache: CacheAdapter = {
  init: () => ({}),
  isDraft: async () => false,
};

/**
 * UNSAFE ON PUBLIC PAGES: always reads staged (unpublished) content, never cached, without
 * draft mode. Only for an internal, authenticated page that lists drafts with their preview links
 * (README "Making links"); anywhere else it publishes your drafts.
 */
export const unsafeStagedCache: CacheAdapter = {
  init: () => ({ cache: "no-store" }),
  isDraft: async () => true,
};

export type ContentSource = "data" | "cdn";

export interface WebflowCmsConfig<S extends WebflowSchema | undefined = undefined> extends WebflowClientConfig {
  /** Runtime schema generated by `next-webflow typegen`. Without it, schemas are fetched from the API. */
  schema?: S;
  /** Needed only to look up collections without a generated schema. Defaults to `WEBFLOW_SITE_ID`. */
  siteId?: string | undefined;
  /**
   * Where published items are read from. `data` (default): Data API, relies on webhooks to
   * invalidate. `cdn`: Content Delivery API, cached up to 300 s by Webflow, no rate limit on hits.
   */
  source?: ContentSource | undefined;
  /**
   * How reads are cached and whether they're drafts. `createWebflow` passes the Next.js data cache
   * (with draft mode). Without it, `createWebflowCms` reads uncached and never in draft mode.
   */
  cache?: CacheAdapter | undefined;
  /** `warn` for problems (stale schema…); optional `debug` for one-time notes (never-published collections). */
  logger?: (Pick<Console, "warn"> & Partial<Pick<Console, "debug">>) | undefined;
  /**
   * `include` reads the whole referenced collection (cached under its collection tag) when it has
   * at most this many items; above it, only the referenced items, by ID. Default `1000`.
   */
  maxIncludeItems?: number | undefined;
  /**
   * During `next build`, `getItemBySlug` finds the slug in the cached collection list instead of
   * one request per page (`buildSlugLookups: "list"`). Above this many items it warns (each page
   * reads the whole cached list) but keeps using the list. Default `5000`.
   */
  maxBuildListItems?: number | undefined;
  /** `list` (default): build-time slug lookups read the cached list. `request`: one `?slug=` request per page. */
  buildSlugLookups?: "list" | "request" | undefined;
  /**
   * Where Option names come from. `live` (default): the collection's schema from the API, cached
   * like content (site + collection tags), so an option renamed in Webflow shows its new name once
   * the collection is invalidated (at the latest on the next `site_publish`), without rerunning
   * typegen. Costs one cached request per collection whose items have Option values.
   * `generated`: only the generated schema; a renamed option keeps its old name until you rerun
   * typegen and redeploy.
   */
  optionNames?: "live" | "generated" | undefined;
}

export type SortBy = "createdOn" | "lastPublished" | "lastUpdated" | "name" | "slug";

/** A type alias (not an interface) so it's assignable to the query serializer's index signature. */
export type FilterOperators = {
  eq?: QueryValue;
  ne?: QueryValue;
  gt?: QueryValue;
  gte?: QueryValue;
  lt?: QueryValue;
  lte?: QueryValue;
  in?: string | readonly string[];
  nin?: string | readonly string[];
  contains?: string;
  ncontains?: string;
  exists?: boolean;
};

export interface ReadOptions {
  /** Locale to read; defaults to the primary locale. */
  cmsLocaleId?: string | undefined;
  signal?: AbortSignal | undefined;
  /**
   * Reference / MultiReference fields (camelCase) to replace with the referenced items, one level
   * deep. Missing or unpublished items become `null` (Reference) or are left out (MultiReference);
   * `{ raw: true }` keeps the original IDs.
   */
  include?: readonly string[] | undefined;
}

export interface GetItemsOptions extends ReadOptions {
  /** Max items to return. Default: all (paginated transparently). */
  limit?: number | undefined;
  offset?: number | undefined;
  sortBy?: SortBy | undefined;
  sortOrder?: "asc" | "desc" | undefined;
  /** Keyed by field name (camelCase) or API slug, e.g. `{ featured: { eq: true } }`. */
  filter?: { [field: string]: FilterOperators | undefined } | undefined;
}

type Raw = { raw: true; include?: undefined };
type NotRaw = { raw?: false | undefined };
type WithInclude<I> = NotRaw & { include: I };
type NoInclude = NotRaw & { include?: undefined };

type CollectionSlug<S extends WebflowSchema> = Extract<keyof S, string>;

/** Functions typed from a generated schema: collection slugs and item fields are inferred. */
export interface TypedWebflowCms<S extends WebflowSchema> {
  getItems<K extends CollectionSlug<S>>(collection: K, options: GetItemsOptions & Raw): Promise<WebflowRawItem[]>;
  getItems<K extends CollectionSlug<S>, const I extends readonly ReferenceKeys<S, K>[]>(
    collection: K,
    options: GetItemsOptions & WithInclude<I>,
  ): Promise<ItemWithIncludes<S, K, I[number]>[]>;
  getItems<K extends CollectionSlug<S>>(collection: K, options?: GetItemsOptions & NoInclude): Promise<ItemOf<S, K>[]>;
  getItemBySlug<K extends CollectionSlug<S>>(
    collection: K,
    slug: string,
    options: ReadOptions & Raw,
  ): Promise<WebflowRawItem | null>;
  getItemBySlug<K extends CollectionSlug<S>, const I extends readonly ReferenceKeys<S, K>[]>(
    collection: K,
    slug: string,
    options: ReadOptions & WithInclude<I>,
  ): Promise<ItemWithIncludes<S, K, I[number]> | null>;
  getItemBySlug<K extends CollectionSlug<S>>(
    collection: K,
    slug: string,
    options?: ReadOptions & NoInclude,
  ): Promise<ItemOf<S, K> | null>;
  getItem<K extends CollectionSlug<S>>(
    collection: K,
    itemId: string,
    options: ReadOptions & Raw,
  ): Promise<WebflowRawItem | null>;
  getItem<K extends CollectionSlug<S>, const I extends readonly ReferenceKeys<S, K>[]>(
    collection: K,
    itemId: string,
    options: ReadOptions & WithInclude<I>,
  ): Promise<ItemWithIncludes<S, K, I[number]> | null>;
  getItem<K extends CollectionSlug<S>>(
    collection: K,
    itemId: string,
    options?: ReadOptions & NoInclude,
  ): Promise<ItemOf<S, K> | null>;
}

/** Functions without a generated schema: any collection slug, fields typed via the generic. */
export interface UntypedWebflowCms {
  getItems(collection: string, options: GetItemsOptions & Raw): Promise<WebflowRawItem[]>;
  getItems<F = UnknownFields>(collection: string, options?: GetItemsOptions & NotRaw): Promise<WebflowItem<F>[]>;
  getItemBySlug(collection: string, slug: string, options: ReadOptions & Raw): Promise<WebflowRawItem | null>;
  getItemBySlug<F = UnknownFields>(
    collection: string,
    slug: string,
    options?: ReadOptions & NotRaw,
  ): Promise<WebflowItem<F> | null>;
  getItem(collection: string, itemId: string, options: ReadOptions & Raw): Promise<WebflowRawItem | null>;
  getItem<F = UnknownFields>(
    collection: string,
    itemId: string,
    options?: ReadOptions & NotRaw,
  ): Promise<WebflowItem<F> | null>;
}

export type WebflowCms<S extends WebflowSchema | undefined> = [S] extends [WebflowSchema]
  ? TypedWebflowCms<S>
  : UntypedWebflowCms;

/** How long a schema fetched from the API is reused in memory (on top of the framework cache). */
const REMOTE_SCHEMA_TTL_MS = 60_000;
const DEFAULT_MAX_INCLUDE_ITEMS = 1000;
const DEFAULT_MAX_BUILD_LIST_ITEMS = 5000;
/** Next.js doesn't put fetch responses over 2 MB in its data cache. */
const NEXT_CACHE_MAX_BYTES = 2 * 1024 * 1024;

interface ReadContext {
  host: WebflowHost;
  draft: boolean;
  init(tags: string[]): FetchInit;
}

export function createWebflowCms<S extends WebflowSchema | undefined = undefined>(
  config: WebflowCmsConfig<S> = {},
): WebflowCms<S> {
  const client = createWebflowClient({
    ...config,
    onResponse: (info) => {
      config.onResponse?.(info);
      watchResponseSize(info);
    },
  });
  const generated: WebflowSchema | undefined = config.schema;
  const maxIncludeItems = config.maxIncludeItems ?? DEFAULT_MAX_INCLUDE_ITEMS;
  const maxBuildListItems = config.maxBuildListItems ?? DEFAULT_MAX_BUILD_LIST_ITEMS;
  const source = config.source ?? "data";
  const optionNames = config.optionNames ?? "live";
  const cache = config.cache ?? noCache;
  const logger = config.logger ?? console;

  const remoteSchemas = new Map<string, { value: Promise<CollectionSchema>; expires: number }>();
  /** Collections whose generated schema turned out to be stale: use the API schema instead. */
  const stale = new Set<string>();
  const warned = new Set<string>();

  const warnOnce = (key: string, message: string) => {
    if (warned.has(key)) return;
    warned.add(key);
    logger.warn(`[next-webflow] ${message}`);
  };
  const debugOnce = (key: string, message: string) => {
    if (warned.has(key)) return;
    warned.add(key);
    logger.debug?.(`[next-webflow] ${message}`);
  };

  function watchResponseSize(info: ResponseInfo): void {
    if (info.init?.cache !== "force-cache" || info.bytes <= NEXT_CACHE_MAX_BYTES) return;
    const path = new URL(info.url).pathname;
    warnOnce(
      `large:${path}`,
      `A ${(info.bytes / 1024 / 1024).toFixed(1)} MB response (${path}) is over the 2 MB limit of the Next.js data ` +
        "cache, so it isn't cached and is fetched again on every render. Pages of 100 items hit this when " +
        "items average over ~20 KB (long rich text).",
    );
  }

  /**
   * Webflow answers 404 (not an empty list) on `/items/live` of a collection that was never
   * published. If the collection exists, treat it as empty; otherwise rethrow. Not memoized:
   * Next.js doesn't cache the 404, and an in-memory memo would outlive the `site_publish`
   * invalidation and freeze `[]` into the regenerated page. The page itself stays cached with
   * the collection tags, so the extra request only happens when it regenerates.
   */
  async function readLive<T>(
    collection: CollectionSchema,
    ctx: ReadContext,
    read: () => Promise<T>,
    empty: T,
  ): Promise<T> {
    if (ctx.draft) return read();
    try {
      return await read();
    } catch (error) {
      if (!(error instanceof WebflowNotFoundError)) throw error;
      await fetchSchemaById(collection.id); // throws if the collection itself doesn't exist
      debugOnce(
        `unpublished:${collection.id}`,
        `Collection "${collection.slug}" has never been published; treating it as empty until it is.`,
      );
      return empty;
    }
  }

  async function context(): Promise<ReadContext> {
    if (await cache.isDraft()) {
      // Staged content only exists on the Data API, and must never be cached.
      return { host: "data", draft: true, init: () => ({ cache: "no-store" }) };
    }
    return { host: source, draft: false, init: (tags) => cache.init(tags) };
  }

  function memo(key: string, load: () => Promise<CollectionSchema>): Promise<CollectionSchema> {
    const hit = remoteSchemas.get(key);
    if (hit && hit.expires > Date.now()) return hit.value;
    const value = load();
    remoteSchemas.set(key, { value, expires: Date.now() + REMOTE_SCHEMA_TTL_MS });
    value.catch(() => remoteSchemas.delete(key));
    return value;
  }

  const fetchSchemaById = (collectionId: string) =>
    memo(`id:${collectionId}`, async () =>
      schemaFromApi(
        await client.request<ApiCollection>(`/collections/${encodeURIComponent(collectionId)}`, {
          init: cache.init(schemaTags(collectionId)),
        }),
      ),
    );

  const fetchSchemaBySlug = (slug: string) =>
    memo(`slug:${slug}`, async () => {
      const siteId = config.siteId ?? readEnv(ENV.siteId);
      if (!siteId) {
        throw new WebflowConfigError(
          `No generated schema for collection "${slug}" and no site ID to look it up. ` +
            `Run \`npx next-webflow typegen\`, or set ${ENV.siteId}.`,
        );
      }
      const { collections } = await client.request<{ collections: ApiCollection[] }>(
        `/sites/${encodeURIComponent(siteId)}/collections`,
        { init: cache.init(schemaTags()) },
      );
      const match = collections.find((collection) => collection.slug === slug);
      if (!match) throw new WebflowConfigError(`Collection "${slug}" not found in site ${siteId}.`);
      return fetchSchemaById(match.id);
    });

  async function resolveCollection(slug: string): Promise<CollectionSchema> {
    const fromGenerated = generated?.[slug];
    if (fromGenerated && !stale.has(slug)) return fromGenerated;
    if (!fromGenerated) {
      warnOnce(
        `missing:${slug}`,
        `No generated schema for collection "${slug}"; fetching it from the API. ` +
          "Run `npx next-webflow typegen` to get types and avoid the extra requests.",
      );
      return fetchSchemaBySlug(slug);
    }
    return fetchSchemaById(fromGenerated.id);
  }

  /**
   * The collection's schema from the API, for Option names. With a framework cache it isn't
   * memoized in memory: the cached response is invalidated with the collection (and by
   * `site_publish`), and an in-memory copy would outlive that and put old names into the
   * regenerated page.
   */
  const fetchLiveSchema = (collectionId: string, ctx: ReadContext): Promise<CollectionSchema> =>
    cache === noCache
      ? fetchSchemaById(collectionId)
      : client
          .request<ApiCollection>(`/collections/${encodeURIComponent(collectionId)}`, {
            // Draft reads are never cached, so previews show the current names too.
            init: ctx.init(schemaTags(collectionId)),
          })
          .then(schemaFromApi);

  /**
   * The generated schema with Option names from the live schema, so options renamed in Webflow
   * show their new names. Option IDs never change on rename; options added after typegen are left
   * to the stale-schema path. If the live schema can't be read, the generated names are used.
   */
  async function withLiveOptionNames(
    slug: string,
    collection: CollectionSchema,
    ctx: ReadContext,
  ): Promise<CollectionSchema> {
    let live: CollectionSchema;
    try {
      live = await fetchLiveSchema(collection.id, ctx);
    } catch (error) {
      // Same key and message as a failed stale-schema refresh: one warning for one outage.
      warnOnce(
        `refresh:${slug}`,
        `Could not fetch the live schema for "${slug}" (${error instanceof Error ? error.message : String(error)}). ` +
          "Serving items with the generated schema.",
      );
      return collection;
    }
    const liveFields = new Map(Object.values(live.fields).map((field) => [field.slug, field]));
    const renamed: string[] = [];
    const fields: Record<string, FieldSchema> = {};
    for (const [key, field] of Object.entries(collection.fields)) {
      const liveField = liveFields.get(field.slug);
      if (!field.options || liveField?.type !== "Option" || !liveField.options) {
        fields[key] = field;
        continue;
      }
      const liveNames = new Map(liveField.options.map((option) => [option.id, option.name]));
      const options = field.options.map((option) => {
        const name = liveNames.get(option.id);
        if (name === undefined || name === option.name) return option;
        renamed.push(`${key}: "${option.name}" → "${name}"`);
        return { id: option.id, name };
      });
      fields[key] = { ...field, options };
    }
    if (renamed.length === 0) return collection;
    warnOnce(
      `renamed:${slug}`,
      `Options renamed in Webflow for "${slug}" (${renamed.join(", ")}); showing the new names. ` +
        "Run `npx next-webflow typegen` to update your types.",
    );
    return { ...collection, fields };
  }

  /** Whether any of these items has a value in an Option field (the only case that needs names). */
  function hasOptionValues(collection: CollectionSchema, raws: WebflowRawItem[]): boolean {
    const optionSlugs = Object.values(collection.fields)
      .filter((field) => field.type === "Option")
      .map((field) => field.slug);
    return (
      optionSlugs.length > 0 && raws.some((raw) => optionSlugs.some((fieldSlug) => raw.fieldData[fieldSlug] != null))
    );
  }

  /** Normalizes items; if the generated schema is stale, retries once with the API schema. */
  async function normalizeAll(
    slug: string,
    collection: CollectionSchema,
    raws: WebflowRawItem[],
    ctx: ReadContext,
  ): Promise<WebflowItem[]> {
    const isGenerated = generated?.[slug] === collection;
    if (isGenerated && optionNames === "live" && hasOptionValues(collection, raws)) {
      collection = await withLiveOptionNames(slug, collection, ctx);
    }
    let results = raws.map((raw) => normalizeItem(raw, collection));
    let mismatch = mergeMismatches(results.map((result) => result.mismatch));

    if (mismatch && isGenerated) {
      warnOnce(
        `stale:${slug}`,
        `The generated schema for "${slug}" is out of date (${describe(mismatch)}). ` +
          "Using the live schema from the API; run `npx next-webflow typegen` to update your types.",
      );
      try {
        const fresh = await fetchSchemaById(collection.id);
        stale.add(slug);
        results = raws.map((raw) => normalizeItem(raw, fresh));
        mismatch = mergeMismatches(results.map((result) => result.mismatch));
      } catch (error) {
        warnOnce(
          `refresh:${slug}`,
          `Could not fetch the live schema for "${slug}" (${error instanceof Error ? error.message : String(error)}). ` +
            "Serving items with the generated schema.",
        );
      }
    }

    if (mismatch && mismatch.unknownOptions.length > 0) {
      warnOnce(
        `options:${slug}`,
        `Unknown Option IDs in "${slug}" (${describe({ unknownFields: [], unknownOptions: mismatch.unknownOptions })}); ` +
          "returning them as { id, name: undefined }.",
      );
    }
    return results.map((result) => result.item);
  }

  /** Filter keys may be camelCase field names or API slugs. `toSearchParams` skips `undefined` and empty filters. */
  function buildQuery(collection: CollectionSchema, options: GetItemsOptions): QueryParams {
    const filter: Record<string, FilterOperators | undefined> = {};
    for (const [key, operators] of Object.entries(options.filter ?? {})) {
      filter[collection.fields[key]?.slug ?? key] = operators;
    }
    return { sortBy: options.sortBy, sortOrder: options.sortOrder, cmsLocaleId: options.cmsLocaleId, filter };
  }

  const itemsPath = (collectionId: string, draft: boolean) =>
    `/collections/${encodeURIComponent(collectionId)}/items${draft ? "" : "/live"}`;

  const emptyList = (): WebflowListResponse<WebflowRawItem> => ({
    items: [],
    pagination: { limit: 0, offset: 0, total: 0 },
  });

  /** Every live (or staged) item of a collection, through the same cached pages as `getItems`. */
  function listAll(
    collection: CollectionSchema,
    ctx: ReadContext,
    options: {
      query: QueryParams;
      limit?: number | undefined;
      offset?: number | undefined;
      signal?: AbortSignal | undefined;
      stopIfTotalOver?: number | undefined;
    },
  ) {
    return readLive(
      collection,
      ctx,
      () =>
        client.paginate<WebflowRawItem>(itemsPath(collection.id, ctx.draft), {
          host: ctx.host,
          query: options.query,
          limit: options.limit,
          offset: options.offset,
          signal: options.signal,
          stopIfTotalOver: options.stopIfTotalOver,
          init: ctx.init(listTags(collection.id)),
        }),
      { items: [] as WebflowRawItem[], total: 0 },
    );
  }

  function assertIncludeAllowed(options: { raw?: boolean | undefined; include?: readonly string[] | undefined }) {
    if (options.raw && options.include?.length) {
      throw new WebflowConfigError("`include` can't be combined with `raw: true` (raw items keep the referenced IDs).");
    }
  }

  async function getItems(slug: string, options: GetItemsOptions & { raw?: boolean } = {}) {
    assertIncludeAllowed(options);
    const [collection, ctx] = await Promise.all([resolveCollection(slug), context()]);
    const { items } = await listAll(collection, ctx, {
      query: buildQuery(collection, options),
      limit: options.limit,
      offset: options.offset,
      signal: options.signal,
    });
    if (options.raw) return items;
    return withIncludes(slug, collection, ctx, await normalizeAll(slug, collection, items, ctx), options);
  }

  async function getItemBySlug(slug: string, itemSlug: string, options: ReadOptions & { raw?: boolean } = {}) {
    assertIncludeAllowed(options);
    const [collection, ctx] = await Promise.all([resolveCollection(slug), context()]);
    let raw: WebflowRawItem | undefined;
    if (!ctx.draft && cache.isBuild?.() && (config.buildSlugLookups ?? "list") === "list") {
      // Build: every prerendered page reads the same cached list (a data cache hit, no API
      // request) instead of one `?slug=` request each. The list fetch also tags the page.
      const { items } = await listAll(collection, ctx, {
        query: buildQuery(collection, { cmsLocaleId: options.cmsLocaleId }),
        signal: options.signal,
      });
      if (items.length > maxBuildListItems) {
        warnOnce(
          `build-list:${slug}`,
          `"${slug}" has ${items.length} items (over maxBuildListItems, ${maxBuildListItems}): every prerendered page ` +
            "reads the whole cached list to find its slug. Prerender a subset in generateStaticParams and render the " +
            'rest on demand (dynamicParams), or set buildSlugLookups: "request" (one API request per page).',
        );
      }
      raw = items.find((item) => item.fieldData.slug === itemSlug);
    } else {
      const { items } = await readLive(
        collection,
        ctx,
        () =>
          client.request<WebflowListResponse<WebflowRawItem>>(itemsPath(collection.id, ctx.draft), {
            host: ctx.host,
            query: { slug: itemSlug, cmsLocaleId: options.cmsLocaleId },
            signal: options.signal,
            init: ctx.init(slugLookupTags(collection.id, itemSlug)),
          }),
        emptyList(),
      );
      raw = items.find((item) => item.fieldData.slug === itemSlug);
    }
    return finishOne(slug, collection, ctx, raw, options);
  }

  async function getItem(slug: string, itemId: string, options: ReadOptions & { raw?: boolean } = {}) {
    assertIncludeAllowed(options);
    const [collection, ctx] = await Promise.all([resolveCollection(slug), context()]);
    return finishOne(slug, collection, ctx, await fetchItemById(collection.id, itemId, ctx, options), options);
  }

  /** A single raw item → `null`, the raw item, or the normalized item with its includes. */
  async function finishOne(
    slug: string,
    collection: CollectionSchema,
    ctx: ReadContext,
    raw: WebflowRawItem | null | undefined,
    options: ReadOptions & { raw?: boolean },
  ) {
    if (!raw) return null;
    if (options.raw) return raw;
    const [item] = await withIncludes(slug, collection, ctx, await normalizeAll(slug, collection, [raw], ctx), options);
    return item ?? null;
  }

  /** One item by ID, tagged with its item tag (also when it 404s, so republishing it invalidates). */
  async function fetchItemById(collectionId: string, itemId: string, ctx: ReadContext, options: ReadOptions) {
    const base = `/collections/${encodeURIComponent(collectionId)}/items/${encodeURIComponent(itemId)}`;
    try {
      return await client.request<WebflowRawItem>(ctx.draft ? base : `${base}/live`, {
        host: ctx.host,
        query: { cmsLocaleId: options.cmsLocaleId },
        signal: options.signal,
        init: ctx.init(itemTags(itemId)),
      });
    } catch (error) {
      if (error instanceof WebflowNotFoundError) return null;
      throw error;
    }
  }

  /** The referenced collection's schema (generated if present) and slug. */
  async function resolveTarget(collectionId: string): Promise<{ slug: string; schema: CollectionSchema }> {
    const generatedSlug = Object.entries(generated ?? {}).find(([, collection]) => collection.id === collectionId)?.[0];
    if (generatedSlug) return { slug: generatedSlug, schema: await resolveCollection(generatedSlug) };
    const schema = await fetchSchemaById(collectionId);
    return { slug: schema.slug, schema };
  }

  /**
   * Referenced items by ID. Up to `maxIncludeItems` in the collection: the whole collection (same
   * cached pages as `getItems`, tagged with the collection tag). Above: only `ids`, by ID, each
   * under its item tag. Drafts always go by ID (nothing is cached).
   */
  async function loadReferenced(collectionId: string, ids: string[], ctx: ReadContext, options: ReadOptions) {
    const { slug, schema } = await resolveTarget(collectionId);
    let raws: WebflowRawItem[];
    const byId = async () =>
      (await Promise.all(ids.map((id) => fetchItemById(collectionId, id, ctx, options)))).filter(
        (raw): raw is WebflowRawItem => raw !== null,
      );
    if (ctx.draft) {
      raws = await byId();
    } else {
      // The first page tells the total; the rest is only fetched when the collection is small enough.
      const list = await listAll(schema, ctx, {
        query: buildQuery(schema, { cmsLocaleId: options.cmsLocaleId }),
        signal: options.signal,
        stopIfTotalOver: maxIncludeItems,
      });
      if (list.total <= maxIncludeItems) {
        // Normalize only what's referenced, not the whole collection.
        const wanted = new Set(ids);
        raws = list.items.filter((raw) => wanted.has(raw.id));
      } else {
        debugOnce(
          `by-id:${collectionId}`,
          `"${slug}" has ${list.total} items (over maxIncludeItems, ${maxIncludeItems}): include reads only the referenced items, by ID.`,
        );
        raws = await byId();
      }
    }
    const items = await normalizeAll(slug, schema, raws, ctx);
    return new Map(items.map((item) => [item.id, item]));
  }

  /** Replaces the `include`d reference fields with the referenced items. */
  async function withIncludes(
    slug: string,
    collection: CollectionSchema,
    ctx: ReadContext,
    items: WebflowItem[],
    options: ReadOptions,
  ): Promise<WebflowItem[]> {
    const include = options.include ?? [];
    if (include.length === 0 || items.length === 0) return items;

    const fields = include.map((key) => {
      const field = collection.fields[key];
      if (!field || (field.type !== "Reference" && field.type !== "MultiReference")) {
        throw new WebflowConfigError(`include: "${key}" is not a Reference or MultiReference field of "${slug}".`);
      }
      if (!field.collectionId) {
        throw new WebflowConfigError(`include: the schema doesn't say which collection "${slug}.${key}" references.`);
      }
      return [key, field as FieldSchema & { collectionId: string }] as const;
    });

    const idsByTarget = new Map<string, Set<string>>();
    for (const [key, field] of fields) {
      const ids = idsByTarget.get(field.collectionId) ?? new Set<string>();
      for (const item of items) for (const id of referenceIds(item.fieldData[key])) ids.add(id);
      idsByTarget.set(field.collectionId, ids);
    }
    const loaded = new Map(
      await Promise.all(
        [...idsByTarget].map(
          async ([collectionId, ids]) =>
            [collectionId, ids.size ? await loadReferenced(collectionId, [...ids], ctx, options) : new Map()] as const,
        ),
      ),
    );

    return items.map((item) => {
      const fieldData: Record<string, unknown> = { ...item.fieldData };
      for (const [key, field] of fields) {
        const found = loaded.get(field.collectionId) ?? new Map<string, WebflowItem>();
        const ids = referenceIds(item.fieldData[key]);
        const resolved = ids.flatMap((id) => found.get(id) ?? []);
        if (resolved.length < ids.length) {
          debugOnce(
            `missing:${slug}.${key}`,
            `Some items referenced by "${slug}.${key}" are missing or unpublished; left out.`,
          );
        }
        fieldData[key] = field.type === "MultiReference" ? resolved : (resolved[0] ?? null);
      }
      return { ...item, fieldData } as WebflowItem;
    });
  }

  return { getItems, getItemBySlug, getItem } as unknown as WebflowCms<S>;
}

function referenceIds(value: unknown): string[] {
  if (typeof value === "string") return [value];
  return Array.isArray(value) ? value.filter((id): id is string => typeof id === "string") : [];
}

function mergeMismatches(mismatches: Array<SchemaMismatch | undefined>): SchemaMismatch | undefined {
  const present = mismatches.filter((mismatch): mismatch is SchemaMismatch => mismatch !== undefined);
  if (present.length === 0) return undefined;
  return {
    unknownFields: [...new Set(present.flatMap((mismatch) => mismatch.unknownFields))],
    unknownOptions: present.flatMap((mismatch) => mismatch.unknownOptions),
  };
}

function describe(mismatch: SchemaMismatch): string {
  const parts: string[] = [];
  if (mismatch.unknownFields.length > 0) parts.push(`unknown fields: ${mismatch.unknownFields.join(", ")}`);
  if (mismatch.unknownOptions.length > 0) {
    parts.push(`unknown options in: ${[...new Set(mismatch.unknownOptions.map((option) => option.field))].join(", ")}`);
  }
  return parts.join("; ");
}
