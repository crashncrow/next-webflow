/** Field types returned by `GET /collections/{id}` (`fields[].type`). */
export type WebflowFieldType =
  | "PlainText"
  | "RichText"
  | "Image"
  | "MultiImage"
  | "VideoLink"
  | "Link"
  | "Email"
  | "Phone"
  | "Number"
  | "DateTime"
  | "Switch"
  | "Color"
  | "Option"
  | "File"
  | "Reference"
  | "MultiReference"
  | "ExtFileRef";

export interface WebflowOption {
  readonly id: string;
  readonly name: string;
}

/**
 * An Option value whose ID isn't in the schema and couldn't be resolved from the API either
 * (e.g. an option added after typegen while the API is unreachable). Its name is unknown.
 */
export interface UnknownOption {
  id: string;
  name: undefined;
}

/** Runtime description of one collection field. Keyed by its camelCase name in `CollectionSchema.fields`. */
export interface FieldSchema {
  /** Field slug as used in the API's `fieldData` (e.g. `post-body`). */
  readonly slug: string;
  readonly type: WebflowFieldType;
  readonly required: boolean;
  /** `Option` fields: possible values (`validations.options`). */
  readonly options?: readonly WebflowOption[];
  /** `Reference` / `MultiReference` fields: the referenced collection. */
  readonly collectionId?: string;
}

export interface CollectionSchema {
  readonly id: string;
  readonly slug: string;
  readonly fields: { readonly [camelKey: string]: FieldSchema };
}

/** Generated by `next-webflow typegen`, keyed by collection slug. */
export type WebflowSchema = { readonly [collectionSlug: string]: CollectionSchema };

export interface WebflowImageValue {
  fileId: string;
  url: string;
  alt?: string | null | undefined;
}

export interface WebflowFileValue {
  fileId: string;
  url: string;
  alt?: string | null | undefined;
}

/**
 * oEmbed data Webflow fetches (through Embedly) for a video link, with camelCase keys. Every key is
 * optional: what's present depends on the provider.
 */
export interface WebflowVideoMetadata {
  title?: string;
  description?: string;
  /** `"video"` for video providers (oEmbed type). */
  type?: string;
  /**
   * Third-party iframe embed HTML (Embedly). Exposed as data only: this library never renders it,
   * and rendering it means trusting the provider's markup.
   */
  html?: string;
  width?: number;
  height?: number;
  /** `width / height`, computed here when both are known (the API's own `aspectRatio` is unreliable). */
  aspectRatio?: number;
  authorName?: string;
  authorUrl?: string;
  providerName?: string;
  providerUrl?: string;
  thumbnailUrl?: string;
  thumbnailWidth?: number;
  thumbnailHeight?: number;
  [key: string]: unknown;
}

/** A `VideoLink` value. The API returns `{ url, metadata }` when reading (writes take a plain URL). */
export interface WebflowVideoValue {
  url: string;
  metadata?: WebflowVideoMetadata;
}

/** Normalized value for each field type (Options are translated per decision 4.2). */
export interface FieldValueMap {
  PlainText: string;
  /** HTML string. */
  RichText: string;
  Image: WebflowImageValue;
  MultiImage: WebflowImageValue[];
  VideoLink: WebflowVideoValue;
  Link: string;
  Email: string;
  Phone: string;
  Number: number;
  /** ISO 8601 string. */
  DateTime: string;
  Switch: boolean;
  Color: string;
  /** `name` is `undefined` only for an unresolvable option (see `UnknownOption`). */
  Option: WebflowOption | UnknownOption;
  File: WebflowFileValue;
  /** Referenced item ID. */
  Reference: string;
  /** Referenced item IDs. */
  MultiReference: string[];
  /** Undocumented shape: treat with care. */
  ExtFileRef: unknown;
}

/**
 * `{ id, name }` narrowed to the exact pairs declared in the schema, plus `UnknownOption` so
 * code has to handle a missing name instead of crashing on it.
 */
type OptionValue<F extends FieldSchema> =
  | (F["options"] extends readonly (infer O)[]
      ? O extends WebflowOption
        ? { id: O["id"]; name: O["name"] }
        : never
      : WebflowOption)
  | UnknownOption;

export type FieldValue<F extends FieldSchema> = F["type"] extends "Option" ? OptionValue<F> : FieldValueMap[F["type"]];

type RequiredKeys<C extends CollectionSchema> = {
  [K in keyof C["fields"]]: C["fields"][K]["required"] extends true ? K : never;
}[keyof C["fields"]];

type Simplify<T> = { [K in keyof T]: T[K] } & {};

/** Normalized `fieldData` for a collection: camelCase keys, optional when not required. */
export type FieldsOf<C extends CollectionSchema> = Simplify<
  { [K in RequiredKeys<C>]: FieldValue<C["fields"][K]> } & {
    [K in Exclude<keyof C["fields"], RequiredKeys<C>>]?: FieldValue<C["fields"][K]>;
  }
>;

/** Every Webflow item has `name` and `slug`. */
export interface BaseFields {
  name: string;
  slug: string;
}

/** Fields of an item when no schema is known: `name` and `slug` plus anything else. */
export type UnknownFields = BaseFields & { [key: string]: unknown };

/** A normalized CMS item. */
export interface WebflowItem<Fields = UnknownFields> {
  id: string;
  cmsLocaleId: string | null;
  /** Can be `null` on live items (`/items/live`) even when published; staged items carry the date. */
  lastPublished: string | null;
  lastUpdated: string;
  createdOn: string;
  isArchived: boolean;
  isDraft: boolean;
  fieldData: Fields;
}

/** An item exactly as the API returns it (`{ raw: true }`). */
export interface WebflowRawItem {
  id: string;
  cmsLocaleId?: string | null;
  lastPublished: string | null;
  lastUpdated: string;
  createdOn: string;
  isArchived: boolean;
  isDraft: boolean;
  fieldData: { name: string; slug: string; [slug: string]: unknown };
}

/** Normalized item type for a collection of a schema. */
export type ItemOf<S extends WebflowSchema, K extends keyof S> = WebflowItem<FieldsOf<S[K]>>;

/** Field keys of collection `K` that hold references (`Reference` or `MultiReference`). */
export type ReferenceKeys<S extends WebflowSchema, K extends keyof S> = Extract<
  {
    [F in keyof S[K]["fields"]]: S[K]["fields"][F]["type"] extends "Reference" | "MultiReference" ? F : never;
  }[keyof S[K]["fields"]],
  string
>;

/** Slug of the schema collection whose ID is `Id` (`never` if it isn't in the schema). */
type SlugById<S extends WebflowSchema, Id> = {
  [K in keyof S]: S[K]["id"] extends Id ? (Id extends S[K]["id"] ? K : never) : never;
}[keyof S];

/** The referenced item type: from the schema when the target collection is in it. */
type ReferencedItem<S extends WebflowSchema, F extends FieldSchema> = [SlugById<S, F["collectionId"]>] extends [never]
  ? WebflowItem
  : ItemOf<S, SlugById<S, F["collectionId"]>>;

/**
 * An included reference: `Reference` → the item, or `null` when it's empty, missing or
 * unpublished; `MultiReference` → the items found, in order (missing ones are left out).
 */
export type IncludedValue<S extends WebflowSchema, F extends FieldSchema> = F["type"] extends "MultiReference"
  ? ReferencedItem<S, F>[]
  : ReferencedItem<S, F> | null;

/** Item type of collection `K` with the reference fields `I` replaced by the referenced items. */
export type ItemWithIncludes<S extends WebflowSchema, K extends keyof S, I extends ReferenceKeys<S, K>> = WebflowItem<
  Simplify<Omit<FieldsOf<S[K]>, I> & { [P in I]: IncludedValue<S, S[K]["fields"][P]> }>
>;
