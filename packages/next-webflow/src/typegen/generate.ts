// Pure code generation for `next-webflow typegen` (no I/O, no Node APIs).
import { WebflowConfigError } from "../core/errors";
import { camelCase, schemaFromApi, type ApiCollection } from "../core/normalize";
import type { CollectionSchema, FieldSchema } from "../core/schema";

export const SCHEMA_FILE = "schema.ts";
export const INDEX_FILE = "index.ts";

const SCHEMA_HEADER = "// Generated by `next-webflow typegen`. Do not edit: rerun the command instead.";
/** Hash of the generated content, so `--check` accepts a file reformatted by Prettier & co. */
const HASH_PREFIX = "// next-webflow-schema-hash: ";

/** Prefix for type names whose collection slug starts with a digit (`2024-events` → `Collection2024EventsItem`). */
const DIGIT_PREFIX = "Collection";

export interface GenerateOptions {
  /** Module the generated files import from. Tests point it at the source. */
  importFrom?: string;
}

export interface GeneratedSchema {
  /** Contents of `schema.ts`. */
  source: string;
  /** Non-fatal problems (e.g. `ExtFileRef` fields, typed `unknown`). */
  warnings: string[];
}

/**
 * `PostsItem` for `posts`, `BlogPostsItem` for `blog-posts`. No singularization: predictable for
 * any language. A leading digit gets the `Collection` prefix so the name is a valid identifier.
 */
export function typeNameForCollection(slug: string): string {
  const pascal = slug
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
  return `${!pascal || /^\d/.test(pascal) ? DIGIT_PREFIX : ""}${pascal}Item`;
}

/** Builds `schema.ts` from `GET /collections/{id}` responses. Output is deterministic (collections sorted by slug). */
export function generateSchemaFile(collections: readonly ApiCollection[], options: GenerateOptions = {}): GeneratedSchema {
  const warnings: string[] = [];
  const schemas = collections
    .map((collection) => {
      assertNoFieldCollisions(collection);
      return schemaFromApi(collection);
    })
    .sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));

  const typeNames = new Map<string, string[]>();
  for (const { slug } of schemas) {
    const name = typeNameForCollection(slug);
    typeNames.set(name, [...(typeNames.get(name) ?? []), slug]);
  }
  const clashes = [...typeNames].filter(([, slugs]) => slugs.length > 1);
  if (clashes.length) {
    throw new WebflowConfigError(
      `Collections map to the same type name: ${clashes
        .map(([name, slugs]) => `${slugs.map((slug) => `"${slug}"`).join(" and ")} → ${name}`)
        .join("; ")}. Rename one of the collection slugs in Webflow.`,
    );
  }

  for (const collection of schemas) {
    for (const [key, field] of Object.entries(collection.fields)) {
      if (field.type === "ExtFileRef") {
        warnings.push(`"${collection.slug}.${key}" is an ExtFileRef field; its values are typed \`unknown\`.`);
      }
    }
  }

  const importFrom = options.importFrom ?? "next-webflow";
  const body = schemas.map((collection) => `  ${propertyKey(collection.slug)}: ${printCollection(collection)},`).join("\n");
  const types = schemas
    .map((collection) => `export type ${typeNameForCollection(collection.slug)} = ItemOf<typeof schema, ${JSON.stringify(collection.slug)}>;`)
    .join("\n");

  const content = [
    `import type { ItemOf, WebflowSchema } from ${JSON.stringify(importFrom)};`,
    "",
    `export const schema = {\n${body}\n} as const satisfies WebflowSchema;`,
    "",
    types,
    "",
  ].join("\n");
  return { source: `${SCHEMA_HEADER}\n${HASH_PREFIX}${hash(content)}\n${content}`, warnings };
}

/** `index.ts`: created once, then owned by the user. Kept minimal so template changes rarely matter. */
export function generateIndexFile(options: GenerateOptions = {}): string {
  return [
    "// Created by `next-webflow typegen`. This file is yours: typegen won't overwrite it (unless --force).",
    "// Types come from ./schema, which typegen regenerates.",
    `import { createWebflow } from ${JSON.stringify(options.importFrom ?? "next-webflow")};`,
    'import { schema } from "./schema";',
    "",
    "export const { getItems, getItemBySlug, getItem } = createWebflow({ schema });",
    'export type * from "./schema";',
    "",
  ].join("\n");
}

/** The hash recorded in a generated `schema.ts`, if any. */
export function readSchemaHash(source: string): string | undefined {
  return source.split("\n").find((line) => line.startsWith(HASH_PREFIX))?.slice(HASH_PREFIX.length).trim();
}

/** FNV-1a (64-bit): change detection, not security. */
function hash(text: string): string {
  let value = 0xcbf29ce484222325n;
  for (const byte of new TextEncoder().encode(text)) {
    value ^= BigInt(byte);
    value = (value * 0x100000001b3n) & 0xffffffffffffffffn;
  }
  return value.toString(16).padStart(16, "0");
}

/** Whether a user-owned `index.ts` still imports the generated schema (otherwise types won't update). */
export function importsGeneratedSchema(indexSource: string): boolean {
  return /from\s+["']\.\/schema(?:\.(?:js|ts))?["']/.test(indexSource);
}

function assertNoFieldCollisions(collection: ApiCollection): void {
  const keys = new Map<string, string[]>();
  for (const field of collection.fields ?? []) {
    if (!field.slug) continue;
    const key = camelCase(field.slug);
    keys.set(key, [...(keys.get(key) ?? []), field.slug]);
  }
  const clashes = [...keys].filter(([, slugs]) => slugs.length > 1);
  if (clashes.length) {
    throw new WebflowConfigError(
      `Collection "${collection.slug ?? collection.id}" has fields that map to the same key: ${clashes
        .map(([key, slugs]) => `${slugs.map((slug) => `"${slug}"`).join(" and ")} → ${key}`)
        .join("; ")}. Rename one of the fields in Webflow.`,
    );
  }
}

function printCollection(collection: CollectionSchema): string {
  const fields = Object.entries(collection.fields)
    .map(([key, field]) => `      ${propertyKey(key)}: ${printField(field)},`)
    .join("\n");
  return [
    "{",
    `    id: ${JSON.stringify(collection.id)},`,
    `    slug: ${JSON.stringify(collection.slug)},`,
    `    fields: {\n${fields}\n    },`,
    "  }",
  ].join("\n");
}

function printField(field: FieldSchema): string {
  const parts = [
    `slug: ${JSON.stringify(field.slug)}`,
    `type: ${JSON.stringify(field.type)}`,
    `required: ${field.required}`,
  ];
  if (field.options) {
    const options = field.options.map((option) => `{ id: ${JSON.stringify(option.id)}, name: ${JSON.stringify(option.name)} }`);
    parts.push(`options: [${options.join(", ")}]`);
  }
  if (field.collectionId) parts.push(`collectionId: ${JSON.stringify(field.collectionId)}`);
  return `{ ${parts.join(", ")} }`;
}

function propertyKey(key: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
}
