// Stand-in for `next-webflow typegen` (stage 5): snapshots the test site's collections into
// src/webflow-schema.ts in the generated-schema format. Run it, THEN add a new Option in Webflow
// to test the stale-schema fallback.
import { writeFileSync } from "node:fs";
import { createWebflowClient, schemaFromApi } from "next-webflow";

const { WEBFLOW_CMS_TOKEN: token, WEBFLOW_SITE_ID: siteId } = process.env;
if (!token || !siteId) throw new Error("Set WEBFLOW_CMS_TOKEN and WEBFLOW_SITE_ID in local.env");

const client = createWebflowClient({ token });
const { collections } = await client.request(`/sites/${siteId}/collections`);
const schema = {};
for (const { id } of collections) {
  const collection = schemaFromApi(await client.request(`/collections/${id}`));
  schema[collection.slug] = collection;
}

const file = new URL("../src/webflow-schema.ts", import.meta.url);
writeFileSync(
  file,
  `// Generated by scripts/snapshot-schema.mjs on ${new Date().toISOString()}. Do not edit.\n` +
    `import type { WebflowSchema } from "next-webflow";\n\n` +
    `export const schema = ${JSON.stringify(schema, null, 2)} as const satisfies WebflowSchema;\n`,
);
console.log(`Wrote ${Object.keys(schema).length} collections to src/webflow-schema.ts`);
